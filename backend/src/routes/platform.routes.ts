import { Router } from 'express';
import * as controller from '../controllers/platform.controller';
import { requireAuth } from '../middleware/auth.middleware';
import { requirePermission } from '../policies/permission.policy';
import { sensitiveLimiter } from './account.routes';
import { validateBody, validateParams, validateQuery } from '../middleware/validate.middleware';
import { membershipIdSchema } from '../validators/membership.validator';
import { adminInviteSchema, adminListSchema, adminUpdateSchema, confirmationSchema, settingsSchema } from '../validators/account.validator';
export const platformRouter = Router();
platformRouter.use(requireAuth, requirePermission('PLATFORM_MANAGE'));
platformRouter.use((_req, res, next) => { res.set('Cache-Control', 'no-store'); next(); });
platformRouter.get('/dashboard', controller.dashboard);
platformRouter.get('/settings', controller.settings);
platformRouter.patch('/settings', sensitiveLimiter, validateBody(settingsSchema), controller.updateSettings);
platformRouter.get('/admins', validateQuery(adminListSchema), controller.list);
platformRouter.post('/admins', sensitiveLimiter, validateBody(adminInviteSchema), controller.invite);
platformRouter.get('/admins/:id', validateParams(membershipIdSchema), controller.detail);
platformRouter.patch('/admins/:id', sensitiveLimiter, validateParams(membershipIdSchema), validateBody(adminUpdateSchema), controller.update);
platformRouter.patch('/admins/:id/disable', sensitiveLimiter, validateParams(membershipIdSchema), validateBody(confirmationSchema), controller.setActive(false));
platformRouter.patch('/admins/:id/enable', sensitiveLimiter, validateParams(membershipIdSchema), validateBody(confirmationSchema), controller.setActive(true));
